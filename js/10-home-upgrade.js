  // ---------- home upgrade: the cozy cabin grows into a timber manor, raising the population cap to 20 ----------
  const HOME_LEVELS = [
    { name: 'Cozy Cabin', pop: 10 },
    { name: 'Timber Manor', pop: 20 }
  ];
  const HOME_UPGRADE_COST = 100;       // gold
  const HOME_UPGRADE_WOOD = 30;        // logs
  const HOME_UPGRADE_SEC = 30;         // seconds of construction
  const HOME_LVL_KEY = 'homeLevel', HOME_END_KEY = 'homeUpgradeEnd';

  let homeLevel = 0;
  try { homeLevel = Math.max(0, Math.min(HOME_LEVELS.length - 1, parseInt(localStorage.getItem(HOME_LVL_KEY), 10) || 0)); } catch (e) {}
  let homeUpgrading = 0;               // timestamp when the current construction finishes
  let finishedWhileAway = false;
  try {
    const end = parseInt(localStorage.getItem(HOME_END_KEY), 10) || 0;
    if (homeLevel < 1 && end > 0) {
      if (end > Date.now()) homeUpgrading = end;
      else { homeLevel = 1; finishedWhileAway = true; }
    }
  } catch (e) {}
  const saveHome = () => {
    try {
      localStorage.setItem(HOME_LVL_KEY, homeLevel);
      if (homeUpgrading) localStorage.setItem(HOME_END_KEY, homeUpgrading);
      else localStorage.removeItem(HOME_END_KEY);
    } catch (e) {}
  };
  const homeCap = () => (HOME_LEVELS[homeLevel] || HOME_LEVELS[0]).pop;
  const homeName = () => (HOME_LEVELS[homeLevel] || HOME_LEVELS[0]).name;

  // CC0 art: "Western-European Medieval Houses (Isometric 2.5D)" by feu, OpenGameArt
  // The manor is generated by art-kit.js with the same palette, light and camera.
  const MANOR = new Image();
  let manorReady = false;
  let homePanelOpen = false;
  MANOR.onload = () => {
    manorReady = true;
    drawHomeThumbs();
    if (homePanelOpen) renderHomePanel(true);
  };
  MANOR.onerror = () => { try { console.warn('Home manor image failed to load: assets/home-manor.png'); } catch (e) {} };
  MANOR.src = ART.buildingData('manor');

  let homeTexCabin = null, homeTexManor = null;
  function currentHomeImage() { return (homeLevel > 0 && manorReady) ? MANOR : HOME; }
  function homeSpriteTexture() {
    if (homeLevel > 0 && manorReady) { if (!homeTexManor) homeTexManor = PX.Texture.from(MANOR); return homeTexManor; }
    if (!homeTexCabin) homeTexCabin = PX.Texture.from(HOME);
    return homeTexCabin;
  }

  // ---- DOM ----
  const homePanel = document.getElementById('homepanel');
  const homeNameEl = document.getElementById('homeName'), homeSubEl = document.getElementById('homeSub');
  const homeNowName = document.getElementById('homeNowName'), homeNowPop = document.getElementById('homeNowPop');
  const homePrev1 = document.getElementById('homePrev1'), homePrev2 = document.getElementById('homePrev2');
  const homeUpgradeBtn = document.getElementById('homeUpgradeBtn'), homeUpgradeCost = document.getElementById('homeUpgradeCost');
  const homeProgressWrap = document.getElementById('homeProgressWrap'), homeProgressFill = document.getElementById('homeProgressFill');
  const homeProgressTime = document.getElementById('homeProgressTime'), homeProgressLabel = document.getElementById('homeProgressLabel');
  const homeNote = document.getElementById('homeNote');
  let lastPanelMs = 0, celebrateT = 0;

  function drawHomeThumbs() {
    if (!homePrev1 || !homePrev2) return;
    const cur = homeLevel > 0 && manorReady ? MANOR.src : HOME.src;
    if (homePrev1.getAttribute('src') !== cur) homePrev1.src = cur;
    if (homePrev2.getAttribute('src') !== MANOR.src) homePrev2.src = MANOR.src;
  }

  const clockText = ms => { const sec = Math.max(0, Math.ceil(ms / 1000)); return Math.floor(sec / 60) + ':' + String(sec % 60).padStart(2, '0'); };

  // ---- the construction clock: a real timer, independent of the render loop ----
  let homeTimerId = 0, homeTickerId = 0;
  function updateHomeProgressUI(left) {
    const pct = Math.min(100, Math.max(0, (1 - Math.max(0, left) / (HOME_UPGRADE_SEC * 1000)) * 100));
    if (homeProgressFill) homeProgressFill.style.transform = 'scaleX(' + (pct / 100).toFixed(4) + ')';
    if (homeProgressTime) homeProgressTime.textContent = clockText(left);
  }
  function stopHomeTimer() {
    if (homeTimerId) { clearTimeout(homeTimerId); homeTimerId = 0; }
    if (homeTickerId) { clearInterval(homeTickerId); homeTickerId = 0; }
  }
  function armHomeTimer() {
    stopHomeTimer();
    if (!homeUpgrading) return;
    const tick = () => {
      const left = homeUpgrading - Date.now();
      if (!homeUpgrading || left <= 0) { stopHomeTimer(); finishHomeUpgrade(true); return; }
      updateHomeProgressUI(left);
    };
    tick();
    homeTickerId = setInterval(tick, 200);
    homeTimerId = setTimeout(tick, Math.max(0, homeUpgrading - Date.now()) + 50);
  }

  function renderHomePanel(force) {
    if (!homePanel) return;
    const now = performance.now();
    if (!force && homePanelOpen && now - lastPanelMs < 250) return;
    lastPanelMs = now;
    const nowMs = Date.now();
    const upgrading = homeUpgrading > nowMs;
    const maxed = homeLevel >= 1 && !upgrading;
    homePanel.classList.toggle('upgrading', upgrading);
    homePanel.classList.toggle('maxed', maxed);

    homeNameEl.textContent = homeName();
    if (upgrading) homeSubEl.textContent = 'Level ' + (homeLevel + 1) + ' · Manor under construction';
    else homeSubEl.textContent = 'Level ' + (homeLevel + 1) + ' · Population ' + population + ' / ' + homeCap();
    homeNowName.textContent = homeName();
    homeNowPop.textContent = String(population);

    if (homeUpgradeCost) homeUpgradeCost.textContent = HOME_UPGRADE_COST + 'g + ' + HOME_UPGRADE_WOOD + 'w';
    const poor = gold < HOME_UPGRADE_COST;
    const poorWood = (typeof woodCount === 'number' ? woodCount : 0) < HOME_UPGRADE_WOOD;
    if (homeUpgradeBtn) {
      homeUpgradeBtn.disabled = poor || poorWood || upgrading || maxed;
      homeUpgradeBtn.title = poor ? ('You need ' + (HOME_UPGRADE_COST - gold) + ' more gold')
        : poorWood ? ('You need ' + (HOME_UPGRADE_WOOD - (woodCount | 0)) + ' more wood') : '';
    }
    if (homeNote) {
      homeNote.textContent = maxed
        ? 'Maximum level reached. Your village thrives.'
        : upgrading
          ? 'Construction continues while you play.'
          : (poor || poorWood)
            ? 'You need ' + (poor ? (HOME_UPGRADE_COST - gold) + ' more gold' : '') + (poor && poorWood ? ' and ' : '') + (poorWood ? (HOME_UPGRADE_WOOD - (woodCount | 0)) + ' more wood' : '') + ' to start the upgrade.'
            : 'A grander home raises your village\u2019s population cap.';
    }
    if (homeProgressWrap) homeProgressWrap.setAttribute('aria-hidden', upgrading ? 'false' : 'true');
    if (upgrading) updateHomeProgressUI(homeUpgrading - nowMs);
    else {
      if (homeProgressFill) homeProgressFill.style.transform = 'scaleX(0)';
      if (homeProgressTime) homeProgressTime.textContent = clockText(HOME_UPGRADE_SEC * 1000);
    }
  }

  function openHomePanel() {
    if (!homePanel) return;
    homePanelOpen = true;
    drawHomeThumbs();
    homePanel.style.display = 'block';
    homePanel.setAttribute('aria-hidden', 'false');
    if (typeof buildPanel !== 'undefined' && buildPanel) { buildPanel.style.display = 'none'; buildBtn.classList.remove('open'); }
    if (window.woodHut) window.woodHut.close();
    if (typeof setTradeOpen === 'function') setTradeOpen(false);
    renderHomePanel(true);
  }
  function closeHomePanel() {
    homePanelOpen = false;
    if (homePanel) { homePanel.style.display = 'none'; homePanel.setAttribute('aria-hidden', 'true'); }
  }

  function startHomeUpgrade() {
    if (!homePanel || homeLevel >= 1 || homeUpgrading > Date.now()) return;
    if (gold < HOME_UPGRADE_COST) { toast('You need ' + HOME_UPGRADE_COST + ' gold to upgrade your home'); renderHomePanel(true); return; }
    if ((typeof woodCount === 'number' ? woodCount : 0) < HOME_UPGRADE_WOOD) { toast('You need ' + HOME_UPGRADE_WOOD + ' wood to upgrade your home'); renderHomePanel(true); return; }
    if (!spendGold(HOME_UPGRADE_COST)) return;
    if (typeof spendWood === 'function') spendWood(HOME_UPGRADE_WOOD);
    homeUpgrading = Date.now() + HOME_UPGRADE_SEC * 1000;
    saveHome();
    armHomeTimer();
    renderHomePanel(true);
    toast('Manor under construction \u2014 ready in ' + HOME_UPGRADE_SEC + 's');
  }

  function finishHomeUpgrade(celebrate) {
    if (homeLevel >= 1) return;
    stopHomeTimer();
    homeLevel = 1;
    homeUpgrading = 0;
    saveHome();
    setStat('pop', ICON.villager, 'Population', population);   // the cap grows; newcomers arrive by growth and feasts
    if (typeof refreshVillageChip === 'function') refreshVillageChip();
    drawHomeThumbs();
    renderHomePanel(true);
    if (celebrate) {
      fxFadeUntil = performance.now() + 750;
      spawnHomeSparks();
      showHomeCelebration();
      toast('Manor complete! Your village can now house 20 people');
    }
  }

  function showHomeCelebration() {
    const el = document.getElementById('homeCelebrate'), fl = document.getElementById('homeFlash');
    if (el) {
      el.classList.remove('on'); void el.offsetWidth; el.classList.add('on');
      clearTimeout(celebrateT); celebrateT = setTimeout(() => el.classList.remove('on'), 4500);
    }
    if (fl) { fl.classList.remove('on'); void fl.offsetWidth; fl.classList.add('on'); }
  }

  // ---- construction FX drawn on the map: scaffolding, dust, smoke, sparks and the progress bar ----
  const homeFxL = world.addChild(new PX.Container());
  const scaffoldG = homeFxL.addChild(new PX.Graphics());
  const dustG = homeFxL.addChild(new PX.Graphics());
  const sparkG = homeFxL.addChild(new PX.Graphics());
  const smokeL = homeFxL.addChild(new PX.Container());
  const progressL = homeFxL.addChild(new PX.Container());
  const progressG = progressL.addChild(new PX.Graphics());
  const progressT = progressL.addChild(timerText());
  progressL.visible = false;

  const smokeTex = radialTex('228,230,232', .55, 48);
  const smokePuffs = [];
  for (let i = 0; i < 7; i++) {
    const s = new PX.Sprite(smokeTex); s.anchor.set(.5); s.tint = 0xd6d7d4; s.alpha = 0; smokeL.addChild(s); smokePuffs.push(s);
  }
  const dustSeeds = [];
  for (let i = 0; i < 18; i++) dustSeeds.push({ off: i / 18, dx: ((i * 37) % 17 - 8) / 8, wob: i * 1.7 });
  const sparks = [];
  let fxFadeUntil = 0, lastFxT = 0, lastFxDraw = -1, scaffoldOn = false, dustOn = false, progressOn = false, sparkOn = false;

  function drawScaffold(R, time, alpha) {
    scaffoldG.clear(); scaffoldG.alpha = alpha;
    const x0 = R.x + R.w * .035, x1 = R.x + R.w * .965;
    const yTop = R.y + R.h * .19, yBot = R.y + R.h * .91;
    const wood = 0x8a5a2f, dark = 0x37220f, hi = 0xc08a4a;
    const line = (ax, ay, bx, by, col, w) => {
      scaffoldG.lineStyle({ width: w, color: col, cap: 'round', join: 'round' });
      scaffoldG.moveTo(ax, ay); scaffoldG.lineTo(bx, by);
    };
    scaffoldG.beginFill(0xffcf6a, .05 + .03 * Math.sin(time * 3));
    scaffoldG.drawEllipse(R.x + R.w / 2, R.y + R.h * .86, R.w * .48, R.h * .08); scaffoldG.endFill();
    for (const x of [x0, x1]) { line(x, yTop, x, yBot, dark, 10); line(x, yTop, x, yBot, wood, 6); line(x - 1, yTop, x - 1, yBot, hi, 1.4); }
    for (const t of [.14, .47, .8]) {
      const y = yTop + (yBot - yTop) * t;
      line(x0, y, x1, y, dark, 8); line(x0, y, x1, y, wood, 4.5); line(x0, y - 1, x1, y - 1, hi, 1);
    }
    for (const [ax, ay, bx, by] of [[x0, yTop, x1, yTop + (yBot - yTop) * .47], [x1, yTop, x0, yTop + (yBot - yTop) * .47]]) {
      line(ax, ay, bx, by, dark, 5); line(ax, ay, bx, by, wood, 2.6);
    }
    line(x0 - 6, yTop, x1 + 6, yTop, dark, 8); line(x0 - 6, yTop, x1 + 6, yTop, wood, 4);
    // pulley and little bucket
    const px = x1 + R.w * .045, py = yTop + R.h * .035, swing = Math.sin(time * 1.4) * 2.4;
    line(x1, yTop, px, py, dark, 3);
    scaffoldG.lineStyle({ width: 1.8, color: 0xd9c08a, alpha: .9 });
    scaffoldG.moveTo(px, py); scaffoldG.lineTo(px + swing, py + R.h * .1);
    scaffoldG.beginFill(0x5a3a1c); scaffoldG.drawCircle(px, py, 3.2); scaffoldG.endFill();
    scaffoldG.beginFill(0x7a502e); scaffoldG.drawRect(px + swing - 3, py + R.h * .1, 6, 5); scaffoldG.endFill();
    scaffoldG.lineStyle({ width: 1.2, color: 0x2f1d0c, alpha: .8 });
    scaffoldG.moveTo(px + swing - 3, py + R.h * .1 + 5); scaffoldG.lineTo(px + swing + 3, py + R.h * .1 + 5);
  }

  function drawDust(R, time) {
    dustG.clear();
    const bx = R.x + R.w * .5, by = R.y + R.h * .9;
    for (const p of dustSeeds) {
      const l = ((time * .24 + p.off) % 1);
      const x = bx + p.dx * R.w * .38 + Math.sin(time * .9 + p.wob) * 3;
      const y = by - l * R.h * .3;
      dustG.beginFill(0xd9c8a8, (1 - l) * .24);
      dustG.drawCircle(x, y, (2 + l * 5) * (R.w / 380));
      dustG.endFill();
    }
  }

  function drawProgress(R, nowMs) {
    progressL.visible = true;
    const total = HOME_UPGRADE_SEC * 1000, left = Math.max(0, homeUpgrading - nowMs), p = Math.min(1, 1 - left / total);
    const bw = 170, bh = 30, cx = R.x + R.w / 2, by = R.y - 34;
    progressG.clear();
    progressG.beginFill(0x000000, .25); progressG.drawRoundedRect(cx - bw / 2 - 2, by + 1, bw + 4, bh + 6, 12); progressG.endFill();
    progressG.lineStyle({ width: 2, color: 0xc99a4b });
    progressG.beginFill(0x2a1a0c); progressG.drawRoundedRect(cx - bw / 2 - 4, by - 3, bw + 8, bh + 6, 12); progressG.endFill();
    progressG.lineStyle(0);
    progressG.beginFill(0x4a321a); progressG.drawRoundedRect(cx - bw / 2, by, bw, bh, 9); progressG.endFill();
    if (p > 0) {
      const w = Math.max(12, bw * p), r = Math.min(9, w / 2);
      progressG.beginFill(0x9a6410); progressG.drawRoundedRect(cx - bw / 2, by, w, bh, r); progressG.endFill();
      progressG.beginFill(0xffb629); progressG.drawRoundedRect(cx - bw / 2, by, w, bh * .72, r); progressG.endFill();
      progressG.beginFill(0xffe27a); progressG.drawRoundedRect(cx - bw / 2 + 3, by + 3, Math.max(6, w - 6), 5, 2.5); progressG.endFill();
    }
    progressG.beginFill(0xffcf6a, .22); progressG.drawCircle(cx + bw / 2 - 3, by + bh / 2, 8); progressG.endFill();
    progressT.position.set(cx, by + bh / 2 + .5);
    const txt = clockText(left);
    if (progressT.text !== txt) progressT.text = txt;
    syncTimerText(progressT);
  }

  function spawnHomeSparks() {
    const R = homeRectP(home.c, home.r);
    const cx = R.x + R.w / 2, cy = R.y + R.h * .42;
    for (let i = 0; i < 42; i++) {
      const a = Math.random() * Math.PI * 2, sp = 45 + Math.random() * 150;
      sparks.push({
        x: cx + (Math.random() - .5) * R.w * .55, y: cy + (Math.random() - .5) * R.h * .35,
        vx: Math.cos(a) * sp * .55, vy: Math.sin(a) * sp * .55 - 90,
        life: .9 + Math.random() * 1.1, max: 2, size: 2 + Math.random() * 4,
        col: [0xffe27a, 0xfff3b0, 0x9af07c, 0xffb347][i % 4]
      });
    }
  }

  function updateSparks(time) {
    const dt = lastFxT ? Math.min(.06, Math.max(0, time - lastFxT)) : 0;
    lastFxT = time;
    if (!sparks.length) { if (sparkOn) { sparkG.clear(); sparkOn = false; } return; }
    sparkOn = true;
    sparkG.clear();
    for (let i = sparks.length - 1; i >= 0; i--) {
      const p = sparks[i];
      p.life -= dt;
      if (p.life <= 0) { sparks.splice(i, 1); continue; }
      p.vy += 210 * dt; p.x += p.vx * dt; p.y += p.vy * dt; p.vx *= .99;
      const a = Math.min(1, p.life / .55);
      sparkG.beginFill(p.col, a * .28); sparkG.drawCircle(p.x, p.y, p.size * 2.1); sparkG.endFill();
      sparkG.beginFill(p.col, a); sparkG.drawCircle(p.x, p.y, p.size * (0.4 + p.life * .7)); sparkG.endFill();
    }
  }

  function updateSmoke(time, R) {
    const on = homeLevel >= 1 && manorReady;
    smokeL.visible = on;
    if (!on) return;
    const cx = R.x + R.w * .255, cy = R.y + R.h * .105;
    for (let i = 0; i < smokePuffs.length; i++) {
      const s = smokePuffs[i], l = ((time * .16 + i / smokePuffs.length) % 1);
      s.position.set(cx + Math.sin(time * .5 + i * 1.7) * R.w * .022 + l * R.w * .13, cy - l * R.h * .72);
      const k = (0.12 + l * .3) * (R.w / 190);
      s.scale.set(k, k); s.alpha = Math.sin(Math.PI * l) * .26; s.tint = 0xe6e2da;
    }
  }

  function updateHomeUpgrade(time) {
    const now = performance.now(), nowMs = Date.now();
    if (homeUpgrading && nowMs >= homeUpgrading) finishHomeUpgrade(true);
    const upgrading = homeUpgrading > nowMs;
    const R = homeRectP(home.c, home.r);
    updateSmoke(time, R);
    const fade = upgrading ? 1 : (fxFadeUntil > now ? (fxFadeUntil - now) / 750 : 0);
    const fxDue = time - lastFxDraw >= 1 / 30 || lastFxDraw < 0;   // construction art only needs 30 redraws a second
    if (fade > 0) { if (fxDue) drawScaffold(R, time, fade); scaffoldOn = true; }
    else if (scaffoldOn) { scaffoldG.clear(); scaffoldG.alpha = 1; scaffoldOn = false; }
    if (upgrading) { if (fxDue) drawDust(R, time); dustOn = true; }
    else if (dustOn) { dustG.clear(); dustOn = false; }
    if (upgrading) { if (fxDue) drawProgress(R, nowMs); progressOn = true; }
    else if (progressOn) { progressL.visible = false; progressG.clear(); progressOn = false; }
    if (fxDue) lastFxDraw = time;
    updateSparks(time);
    if (homePanelOpen) renderHomePanel(false);
  }

  // ---- panel + buttons ----
  if (homeClose) homeClose.addEventListener('click', closeHomePanel);
  if (homeUpgradeBtn) homeUpgradeBtn.addEventListener('click', startHomeUpgrade);
  window.addEventListener('pointerdown', e => {
    if (homePanelOpen && homePanel && !homePanel.contains(e.target)) closeHomePanel();
  }, true);
  document.addEventListener('keydown', e => { if (e.key === 'Escape' && homePanelOpen) closeHomePanel(); });
  try { if (tradeBtn) tradeBtn.addEventListener('click', closeHomePanel); } catch (e) {}
  try { if (buildBtn) buildBtn.addEventListener('click', closeHomePanel); } catch (e) {}

  // ---- resume / apply saved level ----
  if (homeLevel >= 1) {
    saveHome();
    setStat('pop', ICON.villager, 'Population', population);   // housing cap only: villagers arrive over time
  }
  drawHomeThumbs();
  if (homeUpgrading) armHomeTimer();                 // resume a construction that was running before a reload
  if (finishedWhileAway) setTimeout(() => { try { toast('Your manor finished while you were away'); } catch (e) {} }, 1600);
  const finishIfDue = () => { if (homeUpgrading && Date.now() >= homeUpgrading) finishHomeUpgrade(true); };
  document.addEventListener('visibilitychange', () => { if (!document.hidden) finishIfDue(); });
  window.addEventListener('focus', finishIfDue);

  // handy hooks for the console and future updates
  window.home = {
    version: 3,
    level: () => homeLevel,
    upgrading: () => homeUpgrading > Date.now(),
    open: openHomePanel,
    close: closeHomePanel,
    upgrade: startHomeUpgrade,
    finishNow: () => finishHomeUpgrade(true)
  };
